// Extra keys to remove from all files
const extraKeysToRemove = ['about.founder', 'aboutPage.readyToWithdraw', 'tokens.showing_plural'];

function setNestedValue(obj, path, value) {
  const keys = path.split('.');
  let current = obj;
  for (let i = 0; i < keys.length - 1; i++) {
    if (!current[keys[i]]) current[keys[i]] = {};
    current = current[keys[i]];
  }
  current[keys[keys.length - 1]] = value;
}

function deleteNestedKey(obj, path) {
  const keys = path.split('.');
  let current = obj;
  for (let i = 0; i < keys.length - 1; i++) {
    if (!current[keys[i]]) return;
    current = current[keys[i]];
  }
  delete current[keys[keys.length - 1]];
}

let totalFixed = 0;

for (const lang of langs) {
  const filePath = `./src/i18n/locales/${lang}.json`;
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  let fixed = 0;

  // Remove extra keys
  for (const key of extraKeysToRemove) {
    deleteNestedKey(data, key);
  }

  // Add missing keys
  const langTranslations = translations[lang] || {};
  for (const [key, value] of Object.entries(langTranslations)) {
    const parts = key.split('.');
    let current = data;
    let exists = true;
    for (const p of parts) {
      if (current[p] === undefined) { exists = false; break; }
      current = current[p];
    }
    if (!exists) {
      setNestedValue(data, key, value);
      fixed++;
    }
  }

  // Apply zh-specific fixes
  if (lang === 'zh') {
    for (const [key, value] of Object.entries(zhFixes)) {
      setNestedValue(data, key, value);
    }
  }

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n');
  console.log(`${lang}.json: ${fixed} keys added, extra keys removed`);
  totalFixed += fixed;
}

